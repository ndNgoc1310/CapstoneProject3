import os

try:
    import galois
except ImportError:
    print("Thư viện 'galois' chưa được cài đặt. Vui lòng chạy: pip install galois")
    exit(1)

def generate_gf_mul():
    print("--- GENERATING GF(2^10) FULL MULTIPLIER ---")
    
    # ---------------------------------------------------------
    # 1. KHỞI TẠO TOÁN HỌC (MATHEMATICAL SETUP)
    # ---------------------------------------------------------
    # GF(2^10) với đa thức nguyên thủy p(x) = x^10 + x^3 + 1 (Dec: 1033)
    gf = galois.GF(2**10, irreducible_poly=1033)
    alpha = gf.primitive_element
    
    # Khởi tạo mảng chứa 10 danh sách, mỗi danh sách đại diện cho phương trình của 1 bit ngõ ra p[k]
    equations = [[] for _ in range(10)]
    
    # ---------------------------------------------------------
    # 2. ÁNH XẠ THUẬT TOÁN (AND-XOR SUPERPOSITION)
    # ---------------------------------------------------------
    # Vòng lặp kép phân rã toàn bộ ma trận nhân
    for i in range(10):       # Duyệt qua các bit của a
        for j in range(10):   # Duyệt qua các bit của b
            
            # Tính V = alpha^(i+j) trong trường GF
            # Mọi phép tính rút gọn modulo p(x) đều được thư viện galois tự động xử lý
            v = alpha ** (i + j)
            v_val = int(v)
            
            # Duyệt chuỗi nhị phân 10-bit của giá trị V
            for k in range(10):
                # Nếu bit thứ k là 1, cặp (a[i] & b[j]) đóng góp vào ngõ ra p[k]
                if (v_val >> k) & 1:
                    equations[k].append(f"(a[{i}] & b[{j}])")
                    
    # ---------------------------------------------------------
    # 3. XỬ LÝ ĐƯỜNG DẪN (RELATIVE PATH RESOLUTION)
    # ---------------------------------------------------------
    script_dir = os.path.dirname(os.path.abspath(__file__))
    target_dir = os.path.abspath(os.path.join(script_dir, "..", "..", "00_rtl", "fec", "common"))
    os.makedirs(target_dir, exist_ok=True)
    
    file_path = os.path.join(target_dir, "gf_mul.sv")
    print(f"Target Output: {file_path}")
    
    # ---------------------------------------------------------
    # 4. GHI FILE SYSTEMVERILOG (CODE GEN)
    # ---------------------------------------------------------
    with open(file_path, "w", encoding="utf-8") as f:
        # Template Header
        f.write("// =========================================================\n")
        f.write("// Auto-generated GF(2^10) General Multiplier\n")
        f.write("// For Reed-Solomon (544, 514)\n")
        f.write("// Auto-generated by Python Script\n")
        f.write("// =========================================================\n\n")
        
        # Module Interface
        f.write("module gf_mul (\n")
        f.write("    input  logic [9:0] a,\n")
        f.write("    input  logic [9:0] b,\n")
        f.write("    output logic [9:0] p\n")
        f.write(");\n")
        
        # In các dòng assign cho từng bit p[k]
        for k in range(10):
            if not equations[k]:
                # Chống lỗi mảng rỗng (mặc dù với Full Multiplier điều này không xảy ra)
                f.write(f"    assign p[{k}] = 1'b0;\n")
            else:
                # Nối tất cả các cụm (a[i] & b[j]) bằng cổng XOR
                rhs = " ^ ".join(equations[k])
                f.write(f"    assign p[{k}] = {rhs};\n")
                
        f.write("\nendmodule : gf_mul\n")
        
    print("-> Thành công! File SystemVerilog gf_mul.sv đã được sinh ra.")

if __name__ == "__main__":
    generate_gf_mul()
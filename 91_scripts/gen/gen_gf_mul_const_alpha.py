import os

try:
    import galois
except ImportError:
    print("Thư viện 'galois' chưa được cài đặt. Vui lòng chạy: pip install galois")
    exit(1)

def generate_gf_mul_const_alpha():
    print("--- GENERATING GF(2^10) CONSTANT MULTIPLIERS FOR ALPHA^i ---")
    
    # ---------------------------------------------------------
    # 1. KHỞI TẠO TOÁN HỌC (MATHEMATICAL SETUP)
    # ---------------------------------------------------------
    # Khởi tạo trường GF(2^10) với đa thức p(x) = x^10 + x^3 + 1 (Dec: 1033)
    gf = galois.GF(2**10, irreducible_poly=1033)
    alpha = gf.primitive_element
    
    # ---------------------------------------------------------
    # 2. XỬ LÝ ĐƯỜNG DẪN (RELATIVE PATH RESOLUTION)
    # ---------------------------------------------------------
    # Xác định thư mục chứa script hiện tại (91_scripts/gen/)
    script_dir = os.path.dirname(os.path.abspath(__file__))
    
    # Lùi về Project Root, trỏ tới 00_rtl/fec/common/
    target_dir = os.path.abspath(os.path.join(script_dir, "..", "..", "00_rtl", "fec", "common"))
    
    # Tự động tạo thư mục nếu nó chưa tồn tại
    os.makedirs(target_dir, exist_ok=True)
    
    file_path = os.path.join(target_dir, "gf_mul_const_alpha.sv")
    print(f"Target Output: {file_path}")
    
    # ---------------------------------------------------------
    # 3. ÁNH XẠ RTL & GHI FILE (RTL MAPPING & CODE GEN)
    # ---------------------------------------------------------
    with open(file_path, "w", encoding="utf-8") as f:
        # Ghi Header
        f.write("// =========================================================\n")
        f.write("// Auto-generated GF(2^10) Constant Multipliers by Alpha^i\n")
        f.write("// For Syndrome and Chien Search blocks in RS(544, 514)\n")
        f.write("// Auto-generated by Python Script\n")
        f.write("// =========================================================\n\n")
        
        # Sinh 30 module từ i = 0 đến 29
        for i in range(30):
            # Tính giá trị thập phân của hằng số Alpha^i
            alpha_pow_i = alpha ** i
            dec_val = int(alpha_pow_i)
            
            f.write(f"// --- Module {i}: Multiplier by Alpha^{i} (Dec: {dec_val}) ---\n")
            f.write(f"module gf_mul_const_alpha{i} (\n")
            f.write(f"    input  logic [9:0] a,\n")
            f.write(f"    output logic [9:0] p\n")
            f.write(f");\n")
            
            # Khởi tạo mảng chứa phương trình XOR cho từng bit ngõ ra p[0] -> p[9]
            equations = [[] for _ in range(10)]
            
            # Chạy vòng lặp k để phân tách sự đóng góp của từng bit a[k]
            for k in range(10):
                # V_k = (alpha^k) * (alpha^i) trong trường Galois
                v_k = (alpha ** k) * alpha_pow_i
                v_k_val = int(v_k)
                
                # Duyệt qua chuỗi nhị phân của V_k để tìm bit 1
                for j in range(10):
                    if (v_k_val >> j) & 1:
                        equations[j].append(f"a[{k}]")
            
            # Xuất chuỗi lệnh assign cho 10 bit ngõ ra
            for j in range(10):
                if not equations[j]:
                    # Nếu mảng rỗng (không bit a[k] nào tham gia), gán về 0.
                    # Lưu ý: Ép kiểu 1'b0 chuẩn xác hơn 10'd0 cho một dây 1-bit.
                    f.write(f"    assign p[{j}] = 1'b0;\n")
                else:
                    # Nối các tín hiệu bằng cổng XOR
                    rhs = " ^ ".join(equations[j])
                    f.write(f"    assign p[{j}] = {rhs};\n")
            
            f.write("endmodule\n\n")
            
    print("-> Thành công! File SystemVerilog đã được sinh ra.")

if __name__ == "__main__":
    generate_gf_mul_const_alpha()
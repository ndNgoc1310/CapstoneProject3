import os
import sys

try:
    import galois
except ImportError:
    print("Lỗi: Thiếu thư viện. Vui lòng chạy lệnh: pip install galois")
    sys.exit(1)

def generate_alpha_inv_multipliers():
    print("--- GENERATING GF(2^10) CONSTANT MULTIPLIERS FOR ALPHA^(-i) ---")
    
    # ---------------------------------------------------------
    # 1. KHỞI TẠO TOÁN HỌC (MATHEMATICAL SETUP)
    # ---------------------------------------------------------
    # GF(2^10) với đa thức nguyên thủy p(x) = x^10 + x^3 + 1 (Dec: 1033)
    GF = galois.GF(2**10, irreducible_poly=1033)
    alpha = GF(2)
    
    sv_code_blocks = []
    
    # Header của file SV
    sv_code_blocks.append("// =========================================================")
    sv_code_blocks.append("// Auto-generated GF(2^10) Constant Multipliers by Alpha^(-i)")
    sv_code_blocks.append("// Auto-generated by Python Script")
    sv_code_blocks.append("// =========================================================\n")
    
    # ---------------------------------------------------------
    # 2. ÁNH XẠ TOÁN HỌC SANG PHẦN CỨNG (BEHAVIORAL TO RTL MAPPING)
    # ---------------------------------------------------------
    # Lặp để sinh 15 module (i = 1 đến 15)
    for i in range(1, 16):
        # Hằng số C_i = alpha^(-i). Do GF(2^10) có 1023 phần tử khác không, alpha^(-i) = alpha^(1023 - i)
        c_i = alpha ** (1023 - i)
        
        # Thêm Header cho mỗi module
        sv_code_blocks.append(f"// --- Module {i}: Multiplier by Alpha^(-{i}) (Dec: {int(c_i)}) ---")
        sv_code_blocks.append(f"module gf_mul_const_alpha_inv{i} (")
        sv_code_blocks.append("    input  logic [9:0] a,")
        sv_code_blocks.append("    output logic [9:0] p")
        sv_code_blocks.append(");")
        
        # Khởi tạo 10 mảng rỗng chứa các toán hạng (terms) cho p[0] đến p[9]
        equations = [[] for _ in range(10)]
        
        # Quét 10 bit của đầu vào 'a'
        for j in range(10):
            # Tính đóng góp của bit a[j]: a[j] đại diện cho alpha^j
            # Đóng góp = alpha^j * c_i
            val = (alpha ** j) * c_i
            val_int = int(val)
            
            # Quét 10 bit của kết quả đóng góp (val_int)
            for k in range(10):
                # Nếu bit thứ k là 1, tức là a[j] có tham gia XOR vào p[k]
                if (val_int >> k) & 1:
                    equations[k].append(f"a[{j}]")
                    
        # Tạo chuỗi assign cho từng bit p[k]
        for k in range(10):
            if not equations[k]:
                # Nếu không có a[j] nào đóng góp, ngõ ra bằng 0
                sv_code_blocks.append(f"    assign p[{k}] = 1'b0;")
            else:
                # Kết nối các toán hạng bằng cổng XOR
                xor_expr = " ^ ".join(equations[k])
                sv_code_blocks.append(f"    assign p[{k}] = {xor_expr};")
                
        sv_code_blocks.append("endmodule\n")
        
    # Kết hợp toàn bộ chuỗi code lại
    final_sv_code = "\n".join(sv_code_blocks)

    # ---------------------------------------------------------
    # 3. XỬ LÝ ĐƯỜNG DẪN & GHI FILE (FILE I/O)
    # ---------------------------------------------------------
    script_dir = os.path.dirname(os.path.abspath(__file__))
    
    # Lùi 2 cấp thư mục, đi vào 00_rtl/fec/common/
    target_dir = os.path.abspath(os.path.join(script_dir, "..", "..", "00_rtl", "fec", "common"))
    os.makedirs(target_dir, exist_ok=True)
    
    file_path = os.path.join(target_dir, "gf_mul_const_alpha_inv.sv")
    
    with open(file_path, "w") as f:
        f.write(final_sv_code)
        
    print("-> THÀNH CÔNG! Đã tạo 15 module nhân hằng số nghịch đảo.")
    print(f"   + Vị trí lưu : {file_path}")

if __name__ == "__main__":
    generate_alpha_inv_multipliers()
    
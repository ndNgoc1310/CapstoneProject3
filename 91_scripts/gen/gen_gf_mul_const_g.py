import os
import numpy as np

try:
    import galois
except ImportError:
    print("Thư viện 'galois' chưa được cài đặt. Vui lòng chạy: pip install galois")
    exit(1)

def generate_gf_mul_const_g():
    print("--- GENERATING GF(2^10) CONSTANT MULTIPLIERS FOR g(x) ---")
    
    # ---------------------------------------------------------
    # 1. KHỞI TẠO TOÁN HỌC (MATHEMATICAL SETUP)
    # ---------------------------------------------------------
    # Khởi tạo trường GF(2^10) với đa thức p(x) = x^10 + x^3 + 1 (1033)
    gf = galois.GF(2**10, irreducible_poly=1033)
    alpha = gf.primitive_element
    
    # Tạo đa thức generator g(x) = (x - a^0)(x - a^1)...(x - a^29)
    # Dùng numpy để sinh mảng các roots
    roots = alpha ** np.arange(30)
    g_poly = galois.Poly.Roots(roots, field=gf)
    
    # Thư viện galois trả về hệ số từ bậc cao nhất (x^30) xuống bậc thấp nhất (x^0).
    # Ta cần đảo ngược mảng để index trùng với bậc của đa thức (index 0 -> x^0).
    coeffs_asc = g_poly.coeffs[::-1]
    
    # Trích xuất 30 hệ số từ g_0 đến g_29 (bỏ qua hệ số g_30 = 1 ở cuối)
    g_coeffs = coeffs_asc[:30]
    
    # ---------------------------------------------------------
    # 2. XỬ LÝ ĐƯỜNG DẪN (PATH RESOLUTION)
    # ---------------------------------------------------------
    # Lấy đường dẫn của file script hiện tại (nằm trong 91_scripts/gen/)
    script_dir = os.path.dirname(os.path.abspath(__file__))
    
    # Lùi về Project Root (../../) sau đó chui vào 00_rtl/fec/common
    target_dir = os.path.abspath(os.path.join(script_dir, "..", "..", "00_rtl", "fec", "common"))
    
    # Tự động tạo thư mục đích nếu chưa tồn tại
    os.makedirs(target_dir, exist_ok=True)
    
    file_path = os.path.join(target_dir, "gf_mul_const_g.sv")
    print(f"Target file: {file_path}")
    
    # ---------------------------------------------------------
    # 3. ÁNH XẠ RTL & GHI FILE (RTL MAPPING & FILE WRITING)
    # ---------------------------------------------------------
    with open(file_path, "w", encoding="utf-8") as f:
        # Ghi Header đúng chuẩn Template
        f.write("// =========================================================\n")
        f.write("// Auto-generated GF(2^10) Constant Multipliers\n")
        f.write("// Generator Polynomial coefficients for RS(544, 514)\n")
        f.write("// Auto-generated by Python Script\n")
        f.write("// =========================================================\n\n")
        
        # Duyệt qua từng hệ số g_i
        for i, g_i in enumerate(g_coeffs):
            f.write(f"module gf_mul_const_g{i} (\n")
            f.write(f"    input  logic [9:0] a,\n")
            f.write(f"    output logic [9:0] p\n")
            f.write(f");\n")
            
            # Khởi tạo mảng chứa phương trình XOR cho 10 bit ngõ ra
            equations = [[] for _ in range(10)]
            
            # Duyệt qua từng bit ngõ vào a[k] (từ 0 đến 9)
            for k in range(10):
                # Tính C_k = (alpha^k) * g_i trong trường GF
                c_k = (alpha ** k) * g_i
                c_k_val = int(c_k)
                
                # Chuyển C_k thành nhị phân, nếu bit thứ j là 1 thì a[k] tham gia vào p[j]
                for j in range(10):
                    if (c_k_val >> j) & 1:
                        equations[j].append(f"a[{k}]")
            
            # Xuất các lệnh assign RTL
            for j in range(10):
                if not equations[j]:
                    # Nếu mảng rỗng (không có bit a[k] nào tham gia), gán = 0
                    # Ghi chú kỹ thuật: Vì p[j] là 1-bit slice, xuất 1'b0 chuẩn RTL hơn là 10'd0
                    f.write(f"    assign p[{j}] = 1'b0;\n")
                else:
                    # Nối các biến bằng toán tử XOR
                    rhs = " ^ ".join(equations[j])
                    f.write(f"    assign p[{j}] = {rhs};\n")
            
            f.write("endmodule\n\n")
            
    print("-> Done! File SystemVerilog đã được sinh ra thành công.")

if __name__ == "__main__":
    generate_gf_mul_const_g()